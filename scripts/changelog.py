#!/usr/bin/env python3
"""Maintain the changelog pages under docs/docs/changelog/.

Usage:
  changelog.py draft <version> [--range REV] [--date YYYY-MM-DD]
  changelog.py sync

`draft` writes <version>.md from the feat and fix commits in the range (the
latest stable tag up to HEAD by default), with a TODO summary. Curate the page
for users, then run `sync`, which rebuilds the index table and the sidebar
entries from the version pages, so neither is edited by hand.
"""

import argparse
import datetime
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGES = ROOT / "docs/docs/changelog"
NAV = ROOT / "docs/zensical.toml"

INDEX_MARKS = ("<!-- >>> RELEASES -->", "<!-- <<< RELEASES -->")
NAV_MARKS = (
    "  # >>> CHANGELOG NAV (generated by scripts/changelog.py)",
    "  # <<< CHANGELOG NAV",
)
VERSION = re.compile(r"^\d+\.\d+\.\d+$")
FRONT = re.compile(r"\A---\n(.*?)\n---\n", re.S)
COMMIT = re.compile(r"^(feat|fix)(?:\(([^)]+)\))?(!)?: (.+)$")
SECTIONS = {"feat": "Added", "fix": "Fixed"}
PLACEHOLDER = "TODO"


def git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], check=True, capture_output=True, text=True, cwd=ROOT
    ).stdout


def front_matter(text: str) -> dict[str, str]:
    match = FRONT.match(text)
    fields = {}
    for line in (match.group(1) if match else "").splitlines():
        key, _, value = line.partition(":")
        fields[key.strip()] = value.strip()
    return fields


def notes(text: str) -> str:
    """The page body without front matter, title and subtitle."""
    body = re.sub(r"<!--.*?-->", "", FRONT.sub("", text, count=1), flags=re.S)
    lines = body.strip().splitlines()
    while lines and (not lines[0].strip() or lines[0].startswith("# ") or lines[0].startswith("*")):
        lines.pop(0)
    return "\n".join(lines).strip()


def versions() -> list[tuple[str, dict[str, str]]]:
    found = [
        (path.stem, front_matter(path.read_text(encoding="utf-8")))
        for path in PAGES.glob("*.md")
        if VERSION.match(path.stem)
    ]
    return sorted(found, key=lambda v: tuple(map(int, v[0].split("."))), reverse=True)


def replace_between(text: str, marks: tuple[str, str], block: str) -> str:
    start, end = (text.index(m) for m in marks)
    return text[: start + len(marks[0])] + "\n" + block + "\n" + text[end:]


def sync() -> None:
    found = versions()
    rows = ["| Version | Date | Highlights |", "| --- | --- | --- |"]
    rows += [
        f"| [{v}]({v}.md) | {meta.get('date', '')} | {meta.get('summary', '')} |"
        for v, meta in found
    ]
    index = PAGES / "index.md"
    index.write_text(
        replace_between(index.read_text(encoding="utf-8"), INDEX_MARKS, "\n".join(rows)),
        encoding="utf-8",
    )
    entries = [f'    {{ "{v}" = "changelog/{v}.md" }},' for v, _ in found]
    NAV.write_text(
        replace_between(NAV.read_text(encoding="utf-8"), NAV_MARKS, "\n".join(entries)),
        encoding="utf-8",
    )


def default_range(version: str) -> str:
    tags = git("tag", "--list", "v[0-9]*", "--sort=-v:refname").split()
    stable = [t for t in tags if "-" not in t and t != f"v{version}"]
    return f"{stable[0]}..HEAD" if stable else "HEAD"


def draft(version: str, rev: str | None, date: str) -> None:
    if not VERSION.match(version):
        sys.exit(f"{version} is not a stable X.Y.Z version")
    target = PAGES / f"{version}.md"
    if target.exists():
        sys.exit(f"{target} already exists")
    entries: dict[str, list[str]] = {name: [] for name in SECTIONS.values()}
    for subject in git("log", "--format=%s", rev or default_range(version)).splitlines():
        match = COMMIT.match(subject)
        if match:
            kind, scope, _, text = match.groups()
            entries[SECTIONS[kind]].append(f"- {scope + ': ' if scope else ''}{text}")
    sections = "\n\n".join(
        f"### {name}\n\n" + "\n".join(items) for name, items in entries.items() if items
    )
    target.write_text(
        f"---\ndate: {date}\nsummary: {PLACEHOLDER}\n---\n\n"
        f"# smelt {version}\n\n*Released {date}*\n\n{sections}\n",
        encoding="utf-8",
    )
    sync()
    print(f"drafted {target}; curate it for users and replace the {PLACEHOLDER} summary")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    drf = sub.add_parser("draft")
    drf.add_argument("version")
    drf.add_argument("--range")
    drf.add_argument("--date", default=datetime.date.today().isoformat())
    sub.add_parser("sync")
    args = parser.parse_args()
    if args.command == "draft":
        draft(args.version.removeprefix("v"), args.range, args.date)
    else:
        sync()


if __name__ == "__main__":
    main()
