fn render_table(out: &mut String, name: &str, icons: &[GeneratedIcon]) {
    out.push_str(&format!("pub(super) const {name}: &[IconEntry] = &[\n"));
    for icon in icons {
        out.push_str("    IconEntry { ");
        out.push_str(&format!("key: {:?}, ", icon.key));
        out.push_str(&format!("icon: {:?}, ", icon.icon));
        out.push_str(&format!("name: {:?}, ", icon.name));
        out.push_str(&format!(
            "dark: (0x{:02x}, 0x{:02x}, 0x{:02x}), ",
            icon.dark.0, icon.dark.1, icon.dark.2
        ));
        out.push_str(&format!(
            "light: (0x{:02x}, 0x{:02x}, 0x{:02x}) ",
            icon.light.0, icon.light.1, icon.light.2
        ));
        out.push_str("},\n");
    }
    out.push_str("];\n");
}
